export { STRINGS };
export const LANGUAGES = Object.keys(STRINGS);

function savedLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    return LANGUAGES.includes(saved) ? saved : null;
  } catch {
    return null; // No storage (blocked, or running outside a browser).
  }
}

let language = savedLanguage() ?? 'en';

export const getLanguage = () => language;

// Text kept in data as { en, ko }.
export const localized = (text) => text?.[language] ?? text?.en ?? null;

export function t(key, values = {}) {
  const text = STRINGS[language][key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => values[name]);
}

// Updates everything marked up in index.html. Text built in JS calls t() itself.
export function applyLanguage() {
  document.documentElement.lang = language;
  for (const node of document.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of document.querySelectorAll('[data-i18n-html]')) node.innerHTML = t(node.dataset.i18nHtml);
  for (const node of document.querySelectorAll('[data-i18n-label]')) {
    node.setAttribute('aria-label', t(node.dataset.i18nLabel));
  }
}

export function setLanguage(next) {
  language = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // Choice just won't survive a reload.
  }
  applyLanguage();
}
